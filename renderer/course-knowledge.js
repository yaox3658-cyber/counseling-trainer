  // —— 检索：按关键词命中 topic/tags/chapter/body，按相关度排序 ——
  function search(q) {
    const tokens = String(q || '').split(/[\s，。？！、；：""''（）()\-/·]+/).filter((t) => t.length >= 1);
    if (!tokens.length) return [];
    const ql = String(q || '').toLowerCase();
    const scored = COURSE_KNOWLEDGE.map((e) => {
      const topic = e.topic.toLowerCase();
      const chapter = (e.chapter || '').toLowerCase();
      const tags = (e.tags || []).join(' ').toLowerCase();
      const body = e.body.toLowerCase();
      let score = 0;
      for (const t of tokens) {
        const tl = t.toLowerCase();
        if (tl && topic.indexOf(tl) !== -1) score += 10;
        if (tl && tags.indexOf(tl) !== -1) score += 6;
        if (tl && chapter.indexOf(tl) !== -1) score += 4;
        if (tl && body.indexOf(tl) !== -1) score += 2;
      }
      if (ql && topic.indexOf(ql) !== -1) score += 5;
      return { e, score };
    }).filter((x) => x.score > 0).sort((a, b) => b.score - a.score);
    return scored.slice(0, 4).map((x) => x.e);
  }

